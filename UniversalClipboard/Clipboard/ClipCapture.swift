import AppKit
import CryptoKit
import ImageIO
import UniformTypeIdentifiers

extension NSPasteboard.PasteboardType {
    /// Set by macOS on items handed over from another device by Universal Clipboard.
    static let remoteClipboard = Self("com.apple.is-remote-clipboard")
    // Markers from nspasteboard.org that password managers and similar apps put on copies.
    static let concealed = Self("org.nspasteboard.ConcealedType")
    static let transient = Self("org.nspasteboard.TransientType")
    static let autoGenerated = Self("org.nspasteboard.AutoGeneratedType")
    static let onePassword = Self("com.agilebits.onepassword")
    static let jpeg = Self(UTType.jpeg.identifier)
    static let heic = Self(UTType.heic.identifier)
}

/// What was read from the pasteboard, before any processing.
struct RawClip: Sendable {
    var copiedAt: Date
    var isRemote: Bool
    var text: String?
    /// Formatted versions of `text` (RTF, HTML, URL), keyed by pasteboard type.
    var richText: [String: Data] = [:]
    var imageData: Data?
    var imageType: String?
}

enum CaptureResult: Sendable {
    case clip(RawClip)
    /// Nothing worth recording: secret, a Finder file, empty, or an unsupported type.
    case ignored
    /// The pasteboard listed data it would not hand over, e.g. because clipboard access is denied.
    case unreadable
}

enum ClipCapture {
    static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [.concealed, .transient, .autoGenerated, .onePassword]
    static let textTypes: Set<NSPasteboard.PasteboardType> = [.string, .rtf, .html]
    static let richTextTypes: [NSPasteboard.PasteboardType] = [.rtf, .html, .URL]
    /// In order of preference: compressed formats first, TIFF (usually uncompressed) last.
    static let imageTypes: [NSPasteboard.PasteboardType] = [.png, .jpeg, .heic, .tiff]

    /// Reads the first item on `pasteboard` and decides whether it should be recorded.
    @MainActor
    static func read(from pasteboard: NSPasteboard, at date: Date = .now) -> CaptureResult {
        guard let item = pasteboard.pasteboardItems?.first else { return .ignored }
        let types = item.types
        let allTypes = Set(types).union(pasteboard.types ?? [])
        // Finder file copies carry the file's icon as their image, not the file's content.
        guard allTypes.isDisjoint(with: ignoredTypes), !allTypes.contains(.fileURL) else { return .ignored }

        let isRemote = allTypes.contains(.remoteClipboard)
        if isRemote {
            Log.capture.notice("Universal Clipboard item types: \(types.map(\.rawValue).joined(separator: ", "), privacy: .public)")
        }

        // Apps list their richest representation first, so whichever comes first decides text vs. image.
        let firstText = types.firstIndex { textTypes.contains($0) }
        let firstImage = types.firstIndex { imageTypes.contains($0) }
        let prefersImage = firstImage.map { image in firstText.map { image < $0 } ?? true } ?? false

        if !prefersImage, types.contains(.string) {
            guard let text = item.string(forType: .string) else { return .unreadable }
            guard text.contains(where: { !$0.isWhitespace }) else { return .ignored }
            var richText: [String: Data] = [:]
            for type in richTextTypes where types.contains(type) {
                richText[type.rawValue] = item.data(forType: type)
            }
            return .clip(RawClip(copiedAt: date, isRemote: isRemote, text: text, richText: richText))
        }

        if let imageType = imageTypes.first(where: types.contains) {
            guard let data = item.data(forType: imageType) else { return .unreadable }
            return .clip(RawClip(copiedAt: date, isRemote: isRemote, imageData: data, imageType: imageType.rawValue))
        }
        return .ignored
    }
}

/// One stored representation of a clip.
struct Blob: Sendable {
    let type: String
    let data: Data
}

/// A clip ready to be stored: hashed, previewed and, for images, converted and thumbnailed.
struct ProcessedClip: Sendable {
    var copiedAt: Date
    var isRemote: Bool
    var kind: ClipItem.Kind
    var preview: String
    var contentHash: String
    var imageWidth: Int?
    var imageHeight: Int?
    var blobs: [Blob]
    var thumbnail: Data?
}

/// CPU-heavy work on captured clips. Safe to run off the main thread.
enum ClipProcessor {
    static let maxBytes = 25 * 1024 * 1024
    static let previewLength = 200
    static let thumbnailMaxPixelSize = 160

    static func process(_ raw: RawClip) -> ProcessedClip? {
        if let text = raw.text {
            return processText(text, raw: raw)
        }
        if let data = raw.imageData, let type = raw.imageType {
            return processImage(data, type: type, raw: raw)
        }
        return nil
    }

    static func preview(for text: String) -> String {
        let collapsed = text.prefix(1_000).split(whereSeparator: \.isWhitespace).joined(separator: " ")
        return String(collapsed.prefix(previewLength))
    }

    private static func processText(_ text: String, raw: RawClip) -> ProcessedClip? {
        let plain = Data(text.utf8)
        guard plain.count <= maxBytes else { return nil }
        // Formatted versions go first so apps that understand them pick them over plain text.
        var blobs = ClipCapture.richTextTypes.compactMap { type in
            raw.richText[type.rawValue].map { Blob(type: type.rawValue, data: $0) }
        }
        if blobs.reduce(plain.count, { $0 + $1.data.count }) > maxBytes {
            blobs = []
        }
        blobs.append(Blob(type: NSPasteboard.PasteboardType.string.rawValue, data: plain))
        return ProcessedClip(
            copiedAt: raw.copiedAt,
            isRemote: raw.isRemote,
            kind: .text,
            preview: preview(for: text),
            contentHash: sha256(plain),
            blobs: blobs
        )
    }

    private static func processImage(_ data: Data, type: String, raw: RawClip) -> ProcessedClip? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil), CGImageSourceGetCount(source) > 0 else {
            return nil
        }
        var stored = Blob(type: type, data: data)
        if type == NSPasteboard.PasteboardType.tiff.rawValue {
            guard let png = encodePNG(from: source) else { return nil }
            stored = Blob(type: NSPasteboard.PasteboardType.png.rawValue, data: png)
        }
        guard stored.data.count <= maxBytes else { return nil }

        let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any]
        return ProcessedClip(
            copiedAt: raw.copiedAt,
            isRemote: raw.isRemote,
            kind: .image,
            preview: "",
            contentHash: sha256(stored.data),
            imageWidth: properties?[kCGImagePropertyPixelWidth] as? Int,
            imageHeight: properties?[kCGImagePropertyPixelHeight] as? Int,
            blobs: [stored],
            thumbnail: thumbnailPNG(from: source)
        )
    }

    private static func encodePNG(from source: CGImageSource) -> Data? {
        let output = NSMutableData()
        guard let destination = CGImageDestinationCreateWithData(output, UTType.png.identifier as CFString, 1, nil) else {
            return nil
        }
        CGImageDestinationAddImageFromSource(destination, source, 0, nil)
        return CGImageDestinationFinalize(destination) ? output as Data : nil
    }

    private static func thumbnailPNG(from source: CGImageSource) -> Data? {
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: thumbnailMaxPixelSize,
        ]
        guard let image = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }
        let output = NSMutableData()
        guard let destination = CGImageDestinationCreateWithData(output, UTType.png.identifier as CFString, 1, nil) else {
            return nil
        }
        CGImageDestinationAddImage(destination, image, nil)
        return CGImageDestinationFinalize(destination) ? output as Data : nil
    }

    private static func sha256(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }
}
